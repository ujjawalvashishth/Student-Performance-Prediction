    with col3:
        internal_assessment = st.number_input("Internal Assessment (%)", min_value=0.0, max_value=100.0, value=75.0)
        midterm_marks = st.number_input("Midterm Marks (%)", min_value=0.0, max_value=100.0, value=72.0)
        
    submitted = st.form_submit_button("Predict Performance")

