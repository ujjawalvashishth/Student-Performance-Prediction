import streamlit as st
from src.predict import predict_student_performance
from src.database import save_prediction

st.title("🤖 Student Performance Prediction")
st.markdown("Enter student academic, behavioral, and demographic metrics below to generate real-time performance forecasts.")

with st.form("prediction_form"):
    col1, col2, col3 = st.columns(3)
    
    with col1:
        student_id = st.text_input("Student ID", value="STU9999")
        age = st.number_input("Age", min_value=15, max_value=35, value=20)
        gender = st.selectbox("Gender", ["Male", "Female", "Other"])
        study_hours = st.number_input("Study Hours per Day", min_value=0.0, max_value=24.0, value=4.5, step=0.5)
        
